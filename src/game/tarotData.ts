export function createTarotInstance(type: TarotType): TarotCard {
  const item = TAROT_CATALOG[type];
  return {
    ...item,
    id: `tarot-${type}-${Math.random().toString(36).substring(2, 7)}`,
  };
}

export function getRandomTarot(): TarotCard {
  const keys = Object.keys(TAROT_CATALOG) as TarotType[];
  const randomKey = keys[Math.floor(Math.random() * keys.length)];
  return createTarotInstance(randomKey);
}

export function getRandomJoker(): Joker {
  const item = JOKERS_CATALOG[Math.floor(Math.random() * JOKERS_CATALOG.length)];
  return {
    ...item,
    id: `${item.id}-${Math.random().toString(36).substring(2, 6)}`,
  };
}
